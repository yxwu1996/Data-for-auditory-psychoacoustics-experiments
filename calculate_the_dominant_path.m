    while kkkk < n_anneal  %start an annealing
        S_initial = 0;  
        S_modified = 0;
        dSdxy = zeros(2,(kkk-2)); 
        for i = 1:(kkk-1)  %calculate the global Onsager-Machlup action
            S_initial = S_initial + Som_i(X(i),X(i+1),Y(i),Y(i+1),I1,I2,f,D,h);
        end
        for i = 1:(kkk-2)  
            dSdxy(1,i) = dSomdx(X(i),X(i+1),X(i+2),Y(i),Y(i+1),Y(i+2),I1,I2,f,D,h); %calculate the derivative at X(i+1)
            dSdxy(2,i) = dSomdy(X(i),X(i+1),X(i+2),Y(i),Y(i+1),Y(i+2),I1,I2,f,D,h); %calculate the derivative at Y(i+1)
        end
        for i = 1:(kkk-2)  %determine the optimization direction based on the action derivative at each point
            if dSdxy(1,i)<0
                X1(i+1) = X(i+1)+0.01*T_anneal;
            elseif dSdxy(1,i)==0
                X1(i+1) = X(i+1);
            elseif dSdxy(1,i)>0
                X1(i+1) = X(i+1)-0.01*T_anneal;
            end
            if X1(i+1)<=0
                X1(i+1)=X(1+i);
            end
            if dSdxy(2,i)<0
                Y1(i+1) = Y(i+1)+0.01*T_anneal;
            elseif dSdxy(2,i)==0
                Y1(i+1) = Y(i+1);
            elseif dSdxy(2,i)>0
                Y1(i+1) = Y(i+1)-0.01*T_anneal;
            end
            if Y1(i+1)<=0
                Y1(i+1)=Y(i+1);
            end
        end
        for i = 1:(kkk-1)  
            S_modified = S_modified + Som_i(X1(i),X1(i+1),Y1(i),Y1(i+1),I1,I2,f,D,h);
        end                        
        if S_modified <= S_initial   %if the optimization successes, iterate the sequence
            X = X1; Y = Y1;
        elseif S_modified > S_initial
            if exp(-(S_modified-S_initial)/(T_anneal)) > (rand()/T_anneal) %anneal                            
                Xsample = randsample(2:(kkk-1),(kkk-1)/7); Ysample = randsample(2:(kkk-1),(kkk-1)/7); 
                %If Metroplis filtering fails, randomly change the values of some positions (starting and ending points are not included in the random sampling)
                for r = Xsample
                    X(r) = X1(r);
                end
                for r = Ysample
                    Y(r) = Y1(r);
                end
            end
        end
        T_anneal = 0.5*(1.05-tanh(0.000025*(kkkk-115000)));  %reduce annealing temperature
        kkkk=kkkk+1;
    end
    X_result(kk,:)=X(:); Y_result(kk,:)=Y(:); %record the results in one annealing calculation
    kk=kk+1;   
end